# ԽՆԴԻՐ 13: Տողի Բառերի Շրջում (Reverse Words in String)
#
# ՊԱՀԱՆՋԸ:
# Տրված է տեքստ (string), որը բաղկացած է բառերից:
# Շրջի՛ր յուրաքանչյուր բառը ԱՌԱՆՁԻՆ-ԱՌԱՆՁԻՆ, բայց բառերի ՀԵՐԹԱԿԱՆՈՒԹՅՈՒՆԸ
# տողի մեջ թո՛ղ ՆՈՒՅՆԸ:
#
# ՕՐԻՆԱԿ:
# Մուտք:  "Hello World Python"
# Ելք:    "olleH dlroW nohtyP"
#
# DIGI.code Օրինակ:
# Մուտք:  "Armath: The Algorithm of the Future"
# Ելք:    ":htamrA ehT mhtiroglA fo eht erutuF"
#
# ԿԱՆՈՆՆԵՐ:
# 1. Բառերը իրարից բաժանված են բացատով (" "):
# 2. Կարող ես օգտագործել տեքստի մեթոդներ (.split() կամ ցիկլեր):
# =============================================================================

text = "Armath: The Algorithm of the Future"
new_text=text.split(" ")
print(new_text)
# ԳՐԻ՛Ր ՔՈ ԿՈԴԸ ԱՅՍՏԵՂ (Ստացի՛ր և տպի՛ր նոր շրջված տողը)
for i in range(0,len(new_text)):
    new_text[i]=new_text[i][::-1]
text=" ".join(new_text)
print(text)
