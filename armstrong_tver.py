import sys
if sys.platform == "win32" and hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

# =============================================================================
# ԽՆԴԻՐ: Արմսթրոնգի թվեր (Armstrong / Narcissistic Numbers)
# =============================================================================
# Թիվը Արմսթրոնգի թիվ է, եթե նրա յուրաքանչյուր թվանշանը բարձրացնելով
# թվի ՆԻՇԵՐԻ ՔԱՆԱԿԻ աստիճան, դրանց գումարը հավասար է հենց այդ թվին:
#
# Օրինակներ:
#   153  -> 3 նիշ -> 1^3 + 5^3 + 3^3 = 1 + 125 + 27 = 153  -> Արմսթրոնգ է
#   9474 -> 4 նիշ -> 9^4 + 4^4 + 7^4 + 4^4 = 9474           -> Արմսթրոնգ է
#   123  -> 3 նիշ -> 1^3 + 2^3 + 3^3 = 36  ≠ 123             -> Արմսթրոնգ Չ

for i in range(1,10001):
    angle=1
    n=i
    sum_number=0
    t=10
    while i>=t:
        t=t*10
        angle=angle+1
    while n>0:
        mod=n%10
        sum_number=sum_number+mod**angle
        n=n//10

    if sum_number==i:
        print(f"{i} Արմսթրոնգ Է")

