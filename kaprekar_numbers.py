#
# ՍԱՀՄԱՆՈՒՄ:
# Թիվը կոչվում է Կապրեկարի թիվ, եթե նրա քառակուսին (n^2) կարելի է
# բաժանել երկու մասի (աջ և ձախ), որոնց գումարը հավասար է հենց այդ թվին:
#
# Բաժանման կանոնը (առանց str-ի, մաթեմատիկորեն)՝
# Եթե թիվն ունի d հատ թվանշան, ապա նրա քառակուսին բաժանվում է.
#   - Աջ մաս՝ քառակուսու վերջին d թվանշանները (square % (10**d))
#   - Ձախ մաս՝ մնացած թվանշանները (square // (10**d))
# Եթե left + right == n (և right > 0), ապա թիվը Կապրեկարի թիվ է:
#
# Օրինակներ:
#   1   -> 1^2 = 1     -> d=1 -> աջ=1, ձախ=0    -> 0 + 1 = 1 (Կապրեկար է)
#   9   -> 9^2 = 81    -> d=1 -> աջ=1, ձախ=8    -> 8 + 1 = 9 (Կապրեկար է)
#   45  -> 45^2 = 2025 -> d=2 -> աջ=25, ձախ=20  -> 20 + 25 = 45 (Կապրեկար է)
#   55  -> 55^2 = 3025 -> d=2 -> աջ=25, ձախ=30  -> 30 + 25 = 55 (Կապրեկար է)
#   297 -> 297^2 = 88209 -> d=3 -> աջ=209, ձախ=88 -> 88 + 209 = 297 (Կապրեկար է)
#
# ԿԱՆՈՆՆԵՐ:
# 1. Չօգտագործել str()
# 2. Ամբողջը լուծել մաթեմատիկական բաժանումներով (% 10**d, // 10**d)
# =============================================================================

# Գրի՛ր քո կոդը այստեղ.

for n in range(1,1001):
    a=n**2
    new=n
    d=1
    while(new>0):
        d=d*10
        new=new//10
    right=a%d
    left=a//d

    if (right+left)==n and right>0:
        print("Կապրեկար է",n)