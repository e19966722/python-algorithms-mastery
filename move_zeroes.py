def move_zeroes(nums):
    # Գրիր քո կոդը այստեղ
    count=nums.count(0)
    for i in range(count):
        print(count)

        nums.remove(0)
        nums.append(0)
    return nums

    
def move_zeroes_linear(nums):
    pos=0
    for i in nums:
        if i!=0:
            nums[pos]=i
            pos+=1
    while pos<len(nums):
        nums[pos]=0
        pos+=1




