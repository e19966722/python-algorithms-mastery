# Արգելվում է ստեղծել նոր ցուցակ (օրինակ՝ res = []):
#
# ՕՐԻՆԱԿՆԵՐ.
# 1. nums = [0, 1, 0, 3, 12]  -> [1, 3, 12, 0, 0]
# 2. nums = [0, 0, 1]         -> [1, 0, 0]
# 3. nums = [1, 2, 3]         -> [1, 2, 3]
