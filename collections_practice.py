# Վարժություն 1 (Lists):
# Տրված է ցուցակ՝
numbers = [5, 12, 3, 8, 12, 9, 20]

# 1. Ջնջիր ցուցակից 3 թիվը (օգտագործիր .remove()):
# 2. Ջնջիր 0-ական ինդեքսի տարրը (օգտագործիր .pop(0)):
# 3. 2-րդ ինդեքսում ավելացրու 99 թիվը (օգտագործիր .insert()):
# 4. Տպիր ստացված numbers ցուցակը:
# 5. Տպիր, թե քանի հատ 12 կա ցուցակում (օգտագործիր .count()):

# Գրիր քո կոդը այստեղ՝
numbers.remove(3)
print("Ջնջելուց հետո:", numbers)
numbers.pop(0)
print("Ջնջելուց հետո:", numbers)     
numbers.insert(2, 99)
print("Ավելացնելուց հետո:", numbers)    
num_count = numbers.count(12)
print("12-ի քանակը:", num_count)
