# ՄԱՍ 2: ԲԱՌԱՐԱՆՆԵՐԻ (DICTIONARIES) ՀԻՄՆԱԿԱՆ ՄԵԹՈԴՆԵՐԸ
# =============================================================================
#
# 1. Ստեղծել և Կարդալ.
#    - d = {}
#    - d["name"] = "Anna"
#    - d.get("age", 0)       -> եթե "age"-ը չկա, տալիս է 0 (առանց սխալի):
#
# 2. Ջնջել.
#    - del d["name"]         -> ջնջում է "name" բանալին:
#    - val = d.pop("name")   -> ջնջում է և վերադարձնում "name"-ի արժեքը:
#
# 3. Պտտվել ցիկլով.
#    - d.keys()              -> բոլոր բանալիները:
#    - d.values()            -> բոլոր արժեքները:
#    - d.items()             -> (key, value) զույգերը:
# =============================================================================

print("\n--- ՕՐԻՆԱԿՆԵՐ DICT-ԵՐԻ ՀԱՄԱՐ ---")
person = {"name": "Alice", "city": "Yerevan"}

# Ավելացնել / Թարմացնել
person["age"] = 25
print("Person:", person)

# Կարդալ .get()-ով
print("Job:", person.get("job", "Not specified"))

# Ջնջել pop-ով
age = person.pop("age")
print("Հեռացված age:", age)
print("Person pop-ից հետո:", person)

