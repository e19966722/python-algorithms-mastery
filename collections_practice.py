# ՄԱՍ 1: ՑՈՒՑԱԿՆԵՐԻ (LISTS) ՀԻՄՆԱԿԱՆ ՄԵԹՈԴՆԵՐԸ
# =============================================================================
#
# 1. Ավելացնել տարրեր.
#    - lst.append(x)         -> x-ն ավելացնում է ցուցակի ՎԵՐՋՈՒՄ:
#    - lst.insert(index, x)  -> x-ը դնում է կոնկրետ index դիրքում (մնացածը շարժվում են աջ):
#    - lst.extend([a, b])    -> միացնում է մեկ այլ ցուցակ վերջից:
#
# 2. Ջնջել տարրեր.
#    - lst.pop()             -> ջնջում և վերադարձնում է ՎԵՐՋԻՆ տարրը:
#    - lst.pop(index)        -> ջնջում և վերադարձնում է տրված index-ի տարրը:
#    - lst.remove(value)     -> ջնջում է առաջին հանդիպած value արժեքը (ոչ թե ինդեքսը):
#    - del lst[index]        -> ջնջում է տրված index-ի տարրը:
#    - lst.clear()           -> ամբողջությամբ դատարկում է ցուցակը:
#
# 3. Որոնում և Հաշվարկ.
#    - x in lst              -> True/False, արդյոք x-ը կա ցուցակում:
#    - lst.index(x)          -> վերադարձնում է x-ի առաջին ինդեքսը (եթե չկա՝ ValueError):
#    - lst.count(x)          -> հաշվում է, թե քանի հատ x կա ցուցակում:
#
# 4. Դասավորում և Շրջում.
#    - lst.sort()            -> տեղում (in-place) սորտավորում է հենց այդ ցուցակը:
#    - sorted(lst)           -> չի փոխում սկզբնականը, վերադարձնում է ՆՈՐ սորտավորված ցուցակ:
#    - lst.reverse()         -> տեղում շրջում է ցուցակը:
#    - lst[::-1]             -> վերադարձնում է շրջված պատճենը (slice):
# =============================================================================

print("--- ՕՐԻՆԱԿՆԵՐ LIST-ԵՐԻ ՀԱՄԱՐ ---")
nums = [10, 20, 30]

# Ավելացնում ենք
nums.append(40)          # [10, 20, 30, 40]
nums.insert(1, 15)       # 1-ին ինդեքսում դնում ենք 15 -> [10, 15, 20, 30, 40]
print("Ավելացնելուց հետո:", nums)

# Ջնջում ենք
last = nums.pop()        # ջնջում է 40-ը
print("Ջնջված վերջին տարրը:", last)
print("Ցուցակը pop-ից հետո:", nums)

nums.remove(20)          # ջնջում ենք 20 արժեքը
print("20-ը remove անելուց հետո:", nums)

