text1 = "silent"
text2 = "listen"    

def anagram(text1,text2):
    count1={}
    count2={}
    if len(text1)!=len(text2):
        return False
    for i in text1:
        if i in count1:
            count1[i]+=1
        else:
            count1[i]=1
    for i in text2:
        if i in count2:
            count2[i]+=1
        else:
            count2[i]=1
    return count1 == count2