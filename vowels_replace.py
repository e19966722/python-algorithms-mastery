# Տրված է տեքստ: Տեքստի բոլոր լատինատառ ձայնավորները (a, e, i, o, u, մեծատառ/փոքրատառ)
# փոխարինի՛ր հետևյալ կանոնով.
#   - Եթե ձայնավորը գտնվում է ԶՈՒՅԳ ինդեքսում (0, 2, 4, ...) -> փոխարինել "*"
#   - Եթե ձայնավորը գտնվում է ԿԵՆՏ ինդեքսում (1, 3, 5, ...) -> փոխարինել "#"
# Մնացած բոլոր տառերը, նշանները և բացատները մնում են ԱՆՓՈՓՈԽ:
#
# ՕՐԻՆԱԿՆԵՐ:
#   "Hello" -> "H#ll*"
#   "Armath: The Algorithm of the Future" ->
#   սպասվող տեքստում A-ն (0-րդ ինդեքս) կդառնա *, e-ն (10-րդ ինդեքս) կդառնա * և այլն:
# =============================================================================

text = "Armath: The Algorithm of the Future"
d="aeiou"
new_text=""
# ԳՐԻ՛Ր ՔՈ ԿՈԴԸ ԱՅՍՏԵՂ
for i in range(0, len(text)):
    if text[i].lower() in d:
        if i%2==0:
            new_text+='*'
        else:
            new_text+="#"
    else:
        new_text+=text[i]
print(new_text)

#կարճ
for i, char in enumerate(text):
    if char.lower() in d:
        new_text += '*' if i % 2 == 0 else '#'
    else:
        new_text += char