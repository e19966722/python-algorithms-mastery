#
# Հիշեցում՝
#   n! (n ֆակտորիալ) = 1 * 2 * 3 * ... * n
#   Հատուկ դեպք՝ 0! = 1
#
# Օրինակներ:
#   1     -> 1! = 1 (Strong է)
#   2     -> 2! = 2 (Strong է)
#   145   -> 1! + 4! + 5! = 1 + 24 + 120 = 145 (Strong է)
#   40585 -> 4! + 0! + 5! + 8! + 5! = 24 + 1 + 120 + 40320 + 120 = 40585 (Strong է)
#
# ԿԱՆՈՆՆԵՐ:
