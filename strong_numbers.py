# Գրի՛ր քո կոդը այստեղ.

def factorial(n):
    if n==0 or n==1:
        return 1
    else:
        return factorial(n-1)*n
for number in range(1,100000):
    new_number=number
    sum_number=0
    while new_number>0:
        m=new_number%10
        new_number=new_number//10
        
        sum_number=sum_number+factorial(m)

    if sum_number==number:
        print("Strong է",number)