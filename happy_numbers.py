# Happy Number — թիվ, որի թվանշանների քառակուսիների գումարը
# բազմիցս կրկնելուց հետո հանգում է 1-ի:
# Եթե ի վերջո 1-ի չի հանգում, ապա թիվն ընկնում է անվերջ ցիկլ:
# Ապացուցված է, որ բոլոր Unhappy թվերն անխուսափելիորեն
# հայտնվում են հենց 4-ի շուրջ փակ ցիկլի մեջ:
# Ուստի ստուգում ենք. եթե 1 → Happy, եթե 4 → Unhappy:


def square(n):
    sum_number = 0
    while sum_number != 1 and sum_number != 4:  # 1 = Happy, 4 = Unhappy ցիկլի մուտք
        sum_number = 0
        while n > 0:
            m = n % 10
            sum_number = sum_number + m ** 2
            n = n // 10
        n = sum_number
        if n == 1:
            return True
    return False


for i in range(1, 101):
    if square(i):
        print(i, "Happy Number!")
